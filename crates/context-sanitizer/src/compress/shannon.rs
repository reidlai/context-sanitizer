/// Computes the unigram Shannon self-information surprisal score:
/// $$I(w) = -\ln P(w)$$
///
/// High-frequency common words return low surprisal ($\le 3.5$), while rare words
/// return [`DEFAULT_RARE_SURPRISAL`] ($10.0$).
#[must_use]
pub fn word_surprisal(word: &str) -> f32 {
    let mut buf = [0u8; 64];
    let len = word.len();
    if len == 0 || len > 64 {
        return DEFAULT_RARE_SURPRISAL;
    }

    // Convert ASCII slice to lowercase on the stack without heap allocation
    for (i, &b) in word.as_bytes().iter().enumerate() {
        buf[i] = b.to_ascii_lowercase();
    }
    let lower_str = match std::str::from_utf8(&buf[..len]) {
        Ok(s) => s,
        Err(_) => return DEFAULT_RARE_SURPRISAL,
    };

    match STATIC_UNIGRAM_SURPRISAL.binary_search_by_key(&lower_str, |&(w, _)| w) {
        Ok(idx) => {
            if let Some(&(_, score)) = STATIC_UNIGRAM_SURPRISAL.get(idx) {
                score
            } else {
                DEFAULT_RARE_SURPRISAL
            }
        }
        Err(_) => DEFAULT_RARE_SURPRISAL,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn static_table_is_sorted() {
        for window in STATIC_UNIGRAM_SURPRISAL.windows(2) {
            assert!(
                window[0].0 < window[1].0,
                "Table not sorted: {} >= {}",
                window[0].0,
                window[1].0
            );
        }
    }

    #[test]
    fn common_words_have_low_surprisal_and_rare_have_high() {
        assert!(word_surprisal("the") < 2.0);
        assert!(word_surprisal("is") < 2.5);
        assert!(word_surprisal("and") < 2.0);
        assert!(word_surprisal("submodular") >= DEFAULT_RARE_SURPRISAL);
        assert!(word_surprisal("AWS_SECRET_KEY") >= DEFAULT_RARE_SURPRISAL);
    }
}
